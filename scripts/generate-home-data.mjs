import { readFile, writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';

export async function generateHomeData() {
  const root = new URL('../', import.meta.url);
  const context = { window: {} };
  for (const file of ['content.js', 'far-east-peoples.js']) {
    runInNewContext(await readFile(new URL(file, root), 'utf8'), context);
  }
  const fields = ['slug', 'name', 'image', 'area', 'areaLabel', 'region', 'cardText', 'summary'];
  const peoples = context.window.MOZAIKA_PEOPLES.map(person => Object.fromEntries(
    fields.filter(field => person[field] !== undefined).map(field => [field, field === 'image' ? person[field].replace(/^\.\.\//, '') : person[field]])
  ));
  await writeFile(new URL('home-peoples.js', root), `// Generated by scripts/generate-home-data.mjs; edit content.js / far-east-peoples.js.\nwindow.MOZAIKA_PEOPLES=${JSON.stringify(peoples)};\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await generateHomeData();
